function ConvertTo-DungeonTokensRaw([byte[]]$Raw, [int]$OpenIndex, [int]$CloseIndex, [int[]]$Dungeons) {
    $prefixLength = ($OpenIndex + 1) * 5
    $suffixOffset = $CloseIndex * 5
    $suffixLength = $Raw.Length - $suffixOffset
    $result = [byte[]]::new($prefixLength + $Dungeons.Length * 5 + $suffixLength)
    [Array]::Copy($Raw, 0, $result, 0, $prefixLength)
    for ($i = 0; $i -lt $Dungeons.Length; $i++) {
        $at = $prefixLength + $i * 5
        $result[$at] = 0
        [BitConverter]::GetBytes([int]$Dungeons[$i]).CopyTo($result, $at + 1)
    }
    [Array]::Copy($Raw, $suffixOffset, $result, $prefixLength + $Dungeons.Length * 5, $suffixLength)
    return ,$result
}

function New-EkalRidingPotionDungeonPlan($Archive) {
    $groups = Get-EkalRidingPotionDungeonGroups
    $d285Set = [System.Collections.Generic.HashSet[int]]::new([int[]]$groups[285])
    $targets = Get-EkalRidingPotionTargets
    $index = [PvfLib.PvfScript]::List($Archive.ReadText('stackable/stackable.lst'))
    $plan = @()
    foreach ($row in $targets) {
        $id = [int]$row[0]
        $relative = [string]$row[1]
        $baselineCount = [int]$row[2]
        $expectedSha = [string]$row[3]
        if (-not $index.ContainsKey($id) -or $index[$id] -cne $relative) {
            throw "Missing or changed ekal riding potion mapping: $id"
        }
        $path = "stackable/$relative"
        $entry = $Archive.FindFile($path)
        if ($null -eq $entry -or $entry.DataType -ne 1) {
            throw "Missing token STK: $path"
        }
        $raw = $Archive.ReadRaw($path)
        $tokens = $Archive.ReadTokens($path)
        if ($raw.Length -le 0 -or $tokens.Count * 5 -ne $raw.Length) {
            throw "Unknown ekal riding potion layout: $path"
        }
        $openIndices = @()
        $closeIndices = @()
        for ($i = 0; $i -lt $tokens.Count; $i++) {
            if ($tokens[$i].Type -ne 3) { continue }
            $tag = $Archive.ResolveString($tokens[$i].Value)
            if ($tag -ceq '[action usable dungeon]') { $openIndices += $i }
            elseif ($tag -ceq '[/action usable dungeon]') { $closeIndices += $i }
        }
        if ($openIndices.Count -ne 1 -or $closeIndices.Count -ne 1 -or $closeIndices[0] -le $openIndices[0] + 1) {
            throw "Missing or duplicate action usable dungeon: $path"
        }
        $openIndex = $openIndices[0]
        $closeIndex = $closeIndices[0]
        for ($i = $openIndex + 1; $i -lt $closeIndex; $i++) {
            if ($tokens[$i].Type -ne 0) {
                throw "Unknown ekal riding potion dungeon token: $path"
            }
        }
        $currentDungeons = @(for ($i = $openIndex + 1; $i -lt $closeIndex; $i++) { [int]$tokens[$i].Value })
        $baselineDungeons = $groups[$baselineCount]
        $extraDungeons = @($baselineDungeons | Where-Object { -not $d285Set.Contains($_) })
        $targetDungeons = [int[]]@($groups[285] + $extraDungeons)
        $currentKey = $currentDungeons -join ','
        $baselineKey = $baselineDungeons -join ','
        $targetKey = $targetDungeons -join ','
        if ($currentKey -cne $baselineKey -and $currentKey -cne $targetKey) {
            throw "Unknown ekal riding potion dungeon list: $path"
        }
        $reconstructed = ConvertTo-DungeonTokensRaw $raw $openIndex $closeIndex $baselineDungeons
        if ([Convert]::ToHexString([Security.Cryptography.SHA256]::HashData($reconstructed)) -cne $expectedSha) {
            throw "Unknown ekal riding potion baseline: $path"
        }
        $patched = $(if ($currentKey -ceq $targetKey) { [byte[]]$raw.Clone() } else { ConvertTo-DungeonTokensRaw $raw $openIndex $closeIndex $targetDungeons })
        $plan += [pscustomobject]@{
            Id = $id
            Path = $path
            RawFile = "$id.stk.raw"
            Raw = $patched
            OpenIndex = $openIndex
            CloseIndex = $closeIndex
            BaselineCount = $baselineCount
            TargetCount = $targetDungeons.Length
            State = $(if ($currentKey -ceq $targetKey) { 'already_applied' } else { 'patched' })
            BeforeSha256 = [Convert]::ToHexString([Security.Cryptography.SHA256]::HashData([byte[]]$raw)).ToLowerInvariant()
            AfterSha256 = [Convert]::ToHexString([Security.Cryptography.SHA256]::HashData($patched)).ToLowerInvariant()
        }
    }
    return $plan
}

function Write-EkalRidingPotionDungeonDelta($Plan, [string]$Directory) {
    $target = [IO.Path]::GetFullPath($Directory)
    if (Test-Path -LiteralPath $target) { throw 'Output already exists.' }
    $parent = [IO.Path]::GetDirectoryName($target)
    [void][IO.Directory]::CreateDirectory($parent)
    $temporaryName = '.ekal-riding-' + [Guid]::NewGuid().ToString('N')
    $temporary = [IO.Path]::GetFullPath((Join-Path $parent $temporaryName))
    try {
        [void][IO.Directory]::CreateDirectory($temporary)
        $replacements = @()
        foreach ($item in $Plan) {
            [IO.File]::WriteAllBytes((Join-Path $temporary $item.RawFile), $item.Raw)
            if ($item.State -eq 'patched') {
                $replacements += [ordered]@{
                    path = $item.Path
                    raw_file = Join-Path $target $item.RawFile
                    expected_before_sha256 = $item.BeforeSha256
                    after_sha256 = $item.AfterSha256
                }
            }
        }
        [IO.File]::WriteAllText((Join-Path $temporary 'manifest.json'),
            (@{ replacements = @($replacements) } | ConvertTo-Json -Depth 5), [Text.UTF8Encoding]::new($false))
        [IO.Directory]::Move($temporary, $target)
    } finally {
        if ([IO.Directory]::Exists($temporary)) {
            $cleanup = [IO.Path]::GetFullPath($temporary)
            if ([IO.Path]::GetDirectoryName($cleanup) -cne $parent -or
                [IO.Path]::GetFileName($cleanup) -cne $temporaryName) { throw 'Unsafe temporary cleanup path.' }
            [IO.Directory]::Delete($cleanup, $true)
        }
    }
}

if ($MyInvocation.InvocationName -eq '.') { return }
if (-not $PvfPath -or -not $PvfLibPath -or -not $OutputDirectory) { throw 'PvfPath, PvfLibPath and OutputDirectory are required.' }
if (Test-Path -LiteralPath $OutputDirectory) { throw 'Output already exists.' }
Add-Type -Path (Resolve-Path -LiteralPath $PvfLibPath).ProviderPath
$archive = [PvfLib.PvfArchive]::Open((Resolve-Path -LiteralPath $PvfPath).ProviderPath)
try {
    $plan = @(New-EkalRidingPotionDungeonPlan $archive)
    Write-EkalRidingPotionDungeonDelta $plan $OutputDirectory
    Write-Output ("PASS ekal riding potions entries={0} patched={1} already_applied={2}" -f $plan.Count,
        @($plan | Where-Object State -eq 'patched').Count, @($plan | Where-Object State -eq 'already_applied').Count)
} finally { $archive.Dispose() }
