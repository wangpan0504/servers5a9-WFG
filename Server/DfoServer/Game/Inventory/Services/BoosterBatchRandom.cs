internal static class BoosterBatchRandom
{
    public static long Next(long trials, long weight, long totalWeight, Random random)
    {
        if (trials == 0 || weight == 0)
            return 0;
        if (weight == totalWeight)
            return trials;
        // 从整数补权计算小概率，避免 1 - p 把极小但非零的权重舍入为零。
        bool complement = weight > totalWeight - weight;
        double p = (double)(complement ? totalWeight - weight : weight) / totalWeight;
        long value = Sample(trials, p, random);
        return complement ? trials - value : value;
    }

    static long Sample(long trials, double p, Random random)
    {
        double ratio = p / (1 - p);
        double scaledRatio = (trials + 1) * ratio;
        long mode = (long)Math.Floor((trials + 1) * p);
        if (mode < 11)
        {
            // 直接构造接近1的CDF会吞掉极小权重；用63位随机数及补偿log(1-x)保留稀有事件。
            // 几何间隔对应原独立试验，平均循环次数为期望命中数+1，不遍历全部trials。
            double logQ = LogOneMinus(p);
            long result = 0;
            while (trials > 0)
            {
                double u = (double)random.NextInt64(long.MaxValue) / long.MaxValue;
                double skipped = Math.Floor(LogOneMinus(u) / logQ);
                if (skipped >= trials)
                    break;
                trials -= (long)skipped + 1;
                result++;
            }
            return result;
        }

        double variance = trials * p * (1 - p);
        double deviation = Math.Sqrt(variance);
        double b = 1.15 + 2.53 * deviation;
        double a = -0.0873 + 0.0248 * b + 0.01 * p;
        double center = trials * p + 0.5;
        double alpha = (2.83 + 5.1 / b) * deviation;
        double vr = 0.92 - 4.2 / b;
        while (true)
        {
            double v = random.NextDouble();
            double u;
            if (v <= 0.86 * vr)
            {
                u = v / vr - 0.43;
                return (long)Math.Floor((2 * a / (0.5 - Math.Abs(u)) + b) * u + center);
            }
            if (v >= vr)
                u = random.NextDouble() - 0.5;
            else
            {
                u = v / vr - 0.93;
                u = (u < 0 ? -0.5 : 0.5) - u;
                v = random.NextDouble() * vr;
            }
            double us = 0.5 - Math.Abs(u);
            if (us <= 0)
                continue;
            double proposed = Math.Floor((2 * a / us + b) * u + center);
            if (proposed < 0 || proposed > trials)
                continue;
            long k = (long)proposed;
            v *= alpha / (a / (us * us) + b);
            long distance = Math.Abs(k - mode);
            if (distance <= 15)
            {
                double f = 1;
                if (mode < k)
                    for (long i = mode + 1; i <= k; i++)
                        f *= scaledRatio / i - ratio;
                else
                    for (long i = k + 1; i <= mode; i++)
                        v *= scaledRatio / i - ratio;
                if (v <= f)
                    return k;
                continue;
            }
            v = Math.Log(v);
            double rho = (distance / variance) * (((distance / 3.0 + 0.625) * distance + 1.0 / 6) / variance + 0.5);
            double t = -((double)distance * distance) / (2 * variance);
            if (v < t - rho)
                return k;
            if (v > t + rho)
                continue;
            double nm = trials - mode + 1;
            double nk = trials - k + 1;
            double h = (mode + 0.5) * Math.Log((mode + 1) / (ratio * nm)) + Correction(mode) + Correction(trials - mode);
            if (v <= h + (trials + 1) * Math.Log(nm / nk) + (k + 0.5) * Math.Log(nk * ratio / (k + 1)) -
                Correction(k) - Correction(trials - k))
                return k;
        }
    }

    static double LogOneMinus(double value)
    {
        // 当前运行时的 LogP1 仍可能先做 1+x 并舍入；接近零时保留输入本身的精度。
        double q = 1 - value;
        return q == 1 ? -value : Math.Log(q) * (-value) / (q - 1);
    }

    static double Correction(long k)
    {
        ReadOnlySpan<double> values = [0.08106146679532726, 0.04134069595540929, 0.02767792568499834,
            0.02079067210376509, 0.01664469118982119, 0.01387612882307075, 0.01189670994589177,
            0.01041126526197209, 0.009255462182712733, 0.008330563433362871];
        if (k < values.Length)
            return values[(int)k];
        double inverse = 1.0 / (k + 1);
        double square = inverse * inverse;
        return (1.0 / 12 - (1.0 / 360 - square / 1260) * square) * inverse;
    }
}
