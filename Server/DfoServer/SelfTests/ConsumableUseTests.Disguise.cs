    static void DisguiseKinds()
    {
        foreach (var (kind, type) in new[] { ("npc", (byte)1), ("monster", (byte)2), ("creature", (byte)3) })
        {
            string[] strings = ["[stackable type]", "[disguise]", "[string data]", kind,
                "[/string data]", "[int data]", "[/int data]"];
            var raw = RecoveryConsumableFile.Parse(500001, "stackable/test.stk",
                [new(3,0),new(6,1),new(0,0),new(3,2),new(6,3),new(3,4),
                    new(3,5),new(0,605),new(0,300),new(3,6)], id => strings[id]);
            var single = RecoveryConsumableCatalog.Read(raw)!.Disguise!;
            That(single.Type == type && single.FormId == 605 && single.Seconds == 300 &&
                single.Allows(type,605) && !single.Allows((byte)(type % 3 + 1),605) && !single.Allows(type,606),
                "单体变身按原生种类映射且校验种类与ID组合：" + kind);
            That(RecoveryConsumableCatalog.Read(raw with { Disguise = new("unknown",605,300) }) is null,
                "未知资源种类不能默认作为怪物消费");
        }
        string[] mixedStrings = ["[stackable type]", "[random disguise]", "[string data]", "monster", "creature",
            "[/string data]", "[int data]", "[/int data]"];
        var mixed = RecoveryConsumableFile.Parse(10002384,"stackable/test-mixed.stk",
            [new(3,0),new(6,1),new(0,0),new(3,2),new(6,3),new(6,4),new(3,5),new(3,6),
                new(0,64703),new(0,300),new(0,191),new(0,300),new(3,7)], id => mixedStrings[id]);
        var pool = RecoveryConsumableCatalog.Read(mixed)!.Disguise!;
        That(pool.Allows(2,64703) && pool.Allows(3,191) && !pool.Allows(2,191) && !pool.Allows(3,64703),
            "混合随机池保留配对关系，不能把两个合法候选的种类和ID交叉拼接");
        That(RecoveryConsumableCatalog.Read(mixed with { RandomDisguises = [new("monster",64703,300),new("creature",191,301)] }) is null &&
            RecoveryConsumableCatalog.Read(mixed with { RandomDisguises = [new("unknown",64703,300)] }) is null,
            "异长池及未知随机种类继续明确拒绝，不猜测持续时间");
    }

